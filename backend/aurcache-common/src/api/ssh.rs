//! The SSH identity the server clones package sources with.

use serde::{Deserialize, Serialize};

/// What the server offers SSH remotes, and which remotes it trusts.
///
/// Nothing secret: the public half of the key, and how host keys are judged.
/// It exists so a key can be added to a remote (as a deploy key, or to an
/// account) without reading the server's log.
#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct SshInfo {
    /// The key offered to every SSH remote.
    pub key: SshKey,
    pub host_keys: HostKeyPolicy,
    /// The host keys trusted, so a fingerprint can be checked against the
    /// one its host publishes: what was recorded on first contact, or what
    /// the operator's file pins.
    pub trusted_hosts: TrustedHosts,
}

/// The server's SSH key, or why it has none.
#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum SshKey {
    Ready {
        /// One line, as it goes into `authorized_keys` or a forge's key form.
        public_key: String,
        /// `SHA256:...`, as `ssh-keygen -l` prints it.
        fingerprint: String,
        origin: KeyOrigin,
        /// Whether the key is opened with the passphrase in
        /// `AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE`. Never the passphrase.
        passphrase_protected: bool,
    },
    /// No key could be loaded; SSH sources fail until this is fixed.
    Unavailable { reason: String },
}

/// Where the server's SSH key came from.
#[derive(Deserialize, Serialize, Clone, Copy, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum KeyOrigin {
    /// Generated by the server on its first start.
    Generated,
    /// Supplied by the operator, through `AURCACHE_GIT_SSH_KEY`.
    Provided,
}

/// How the server decides whether to trust an SSH host.
#[derive(Deserialize, Serialize, Clone, Copy, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum HostKeyPolicy {
    /// Only the hosts in the operator's `AURCACHE_SSH_KNOWN_HOSTS`.
    Pinned,
    /// A host's key is recorded the first time it is seen, and any other key
    /// it presents later is refused.
    TrustOnFirstUse,
}

/// The host keys the server trusts, as the file it judges them by lists
/// them; or why that file could not be read.
#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum TrustedHosts {
    /// Every entry that vouches for a key, in the file's order. Empty before
    /// the first host is recorded. `@revoked` and `@cert-authority` lines
    /// vouch for none and are left out.
    Listed { hosts: Vec<TrustedHost> },
    /// The file could not be read, and every SSH source fails until it can.
    Unreadable { reason: String },
}

/// One host key the server trusts.
#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct TrustedHost {
    /// The hosts it is trusted for, as the file writes them: `github.com`,
    /// `[git.example.com]:2222`, or a list of patterns. `None` for a hashed
    /// entry, which does not say.
    pub names: Option<String>,
    /// `ssh-ed25519`, `ecdsa-sha2-nistp256`, ...
    pub key_type: String,
    /// `SHA256:...`, as `ssh-keygen -l` prints it and forges publish it.
    pub fingerprint: String,
}
