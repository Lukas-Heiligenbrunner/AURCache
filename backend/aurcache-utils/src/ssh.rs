/// Filename of the key the server generates.
const KEY_FILE: &str = "id_ed25519";
/// Filename of the host keys trusted on first use.
const KNOWN_HOSTS_FILE: &str = "known_hosts";
/// The comment the generated key carries, which is what a forge's key list
/// shows next to it.
const KEY_COMMENT: &str = "aurcache-server";

/// Which SSH key the server uses, and where it came from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeySource {
    /// Named by the operator; never generated or overwritten.
    Provided(PathBuf),
    /// Generated by the server, on its first start, if absent.
    Generated(PathBuf),
}

impl KeySource {
    /// The key this deployment is configured with.
    #[must_use]
    pub fn configured() -> Self {
        match AURCACHE_GIT_SSH_KEY.get_os().filter(|v| !v.is_empty()) {
            Some(path) => Self::Provided(PathBuf::from(path)),
            None => Self::Generated(aurcache_common::fs::ssh_dir().join(KEY_FILE)),
        }
    }

    #[must_use]
    pub fn path(&self) -> &Path {
        match self {
            Self::Provided(path) | Self::Generated(path) => path,
        }
    }

    const fn origin(&self) -> KeyOrigin {
        match self {
            Self::Provided(_) => KeyOrigin::Provided,
            Self::Generated(_) => KeyOrigin::Generated,
        }
    }
}

/// Where host keys are judged from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HostKeySource {
    /// The operator's file: only what it lists is trusted, and it is never
    /// written to.
    Pinned(PathBuf),
    /// The server's own file, which a host is added to on first contact.
    TrustOnFirstUse(PathBuf),
}

impl HostKeySource {
    /// The policy this deployment is configured with.
    #[must_use]
    pub fn configured() -> Self {
        match AURCACHE_SSH_KNOWN_HOSTS.get_os().filter(|v| !v.is_empty()) {
            Some(path) => Self::Pinned(PathBuf::from(path)),
            None => Self::TrustOnFirstUse(aurcache_common::fs::ssh_dir().join(KNOWN_HOSTS_FILE)),
        }
    }

    fn path(&self) -> &Path {
        match self {
            Self::Pinned(path) | Self::TrustOnFirstUse(path) => path,
        }
    }
}

/// How a deployment configures the server's SSH: the key, the file holding
/// its passphrase if it has one, and where host keys are judged from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SshConfig {
    /// The server's own SSH directory: where it generates its key and records
    /// host keys unless told otherwise, and where a restored key goes.
    pub dir: PathBuf,
    pub key: KeySource,
    pub passphrase_file: Option<PathBuf>,
    pub hosts: HostKeySource,
}

impl SshConfig {
    /// What this deployment's environment says.
    #[must_use]
    pub fn configured() -> Self {
        Self {
            dir: aurcache_common::fs::ssh_dir(),
            key: KeySource::configured(),
            passphrase_file: AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE
                .get_os()
                .filter(|v| !v.is_empty())
                .map(PathBuf::from),
            hosts: HostKeySource::configured(),
        }
    }
}

/// A key's passphrase, wiped from memory when dropped and never printed.
#[derive(Clone)]
pub(crate) struct Passphrase(Zeroizing<String>);

impl Passphrase {
    /// The passphrase in the file at `path`: its first line, so the newline
    /// an editor or `echo` leaves at the end is not taken as part of it.
    fn read(path: &Path) -> anyhow::Result<Self> {
        let text = Zeroizing::new(fs::read_to_string(path).with_context(|| {
            format!(
                "{AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE} points at {}, which cannot be read",
                path.display()
            )
        })?);
        let first = text.lines().next().unwrap_or_default();
        Ok(Self(Zeroizing::new(first.to_string())))
    }

    pub(crate) fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Debug for Passphrase {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Passphrase(<redacted>)")
    }
}

/// A usable SSH key: where its private half is, its public half, and the
/// passphrase that opens it if it needs one.
#[derive(Debug, Clone)]
pub struct Identity {
    private_key: PathBuf,
    public_key: PublicKey,
    origin: KeyOrigin,
    passphrase: Option<Passphrase>,
}

impl Identity {
    #[must_use]
    pub fn private_key(&self) -> &Path {
        &self.private_key
    }

    /// The passphrase to open the key with, for a key that needs one.
    pub(crate) fn passphrase(&self) -> Option<&str> {
        self.passphrase.as_ref().map(Passphrase::as_str)
    }

    /// The public key on one line, as a forge's "add key" form takes it.
    #[must_use]
    pub fn public_key_line(&self) -> String {
        self.public_key
            .to_openssh()
            .unwrap_or_else(|_| self.public_key.algorithm().to_string())
    }

    /// `SHA256:...`, as `ssh-keygen -l` prints it.
    #[must_use]
    pub fn fingerprint(&self) -> String {
        self.public_key.fingerprint(HashAlg::Sha256).to_string()
    }
}

/// The server's key, or why it has none.
#[derive(Debug, Clone)]
enum Key {
    Ready(Identity),
    Unavailable(String),
}

/// Everything the server reaches an SSH remote with: its key, and the host
/// keys it trusts.
#[derive(Debug)]
pub struct SshAccess {
    /// What the key was loaded from. `None` for access built without any.
    config: Option<SshConfig>,
    /// Behind a lock so that a key a restore put in place is used, and
    /// reported, without a restart.
    key: RwLock<Key>,
    hosts: HostKeys,
}

impl SshAccess {
    /// The key and host-key policy this deployment is configured with,
    /// generating the key on first start.
    ///
    /// Never fails: a server without a usable key still serves everything
    /// that does not need one, and each SSH source then fails saying why.
    /// A host trusted on first use is recorded in `log`.
    #[must_use]
    pub fn load(log: ActivityLog) -> Self {
        let access = Self::new(SshConfig::configured()).with_log(log);
        access.log();
        access
    }

    /// What `config` describes, generating the key first if it is ours to
    /// generate and missing.
    ///
    /// No key at all when the linked libgit2 cannot use one: SSH sources
    /// then fail saying so, rather than connecting without the server's key
    /// or its host-key checks.
    #[must_use]
    pub fn new(config: SshConfig) -> Self {
        Self {
            key: RwLock::new(load_key(&config)),
            hosts: HostKeys::new(config.hosts.clone()),
            config: Some(config),
        }
    }

    /// Record each host trusted on first use in `log`. Without one it is
    /// written to the journal only.
    #[must_use]
    pub fn with_log(mut self, log: ActivityLog) -> Self {
        self.hosts.log = log;
        self
    }

    /// Access with no key at all, for a store that is never meant to reach an
    /// SSH remote.
    #[must_use]
    pub fn unavailable(reason: impl Into<String>) -> Self {
        Self {
            config: None,
            key: RwLock::new(Key::Unavailable(reason.into())),
            hosts: HostKeys::new(HostKeySource::Pinned(PathBuf::new())),
        }
    }

    fn key(&self) -> std::sync::RwLockReadGuard<'_, Key> {
        self.key
            .read()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    /// The key to offer, or why there is none.
    pub(crate) fn identity(&self) -> Result<Identity, String> {
        match &*self.key() {
            Key::Ready(identity) => Ok(identity.clone()),
            Key::Unavailable(reason) => Err(reason.clone()),
        }
    }

    pub(crate) fn hosts(&self) -> &HostKeys {
        &self.hosts
    }

    /// What the API reports: nothing secret.
    #[must_use]
    pub fn info(&self) -> SshInfo {
        let key = match &*self.key() {
            Key::Ready(identity) => SshKey::Ready {
                public_key: identity.public_key_line(),
                fingerprint: identity.fingerprint(),
                origin: identity.origin,
                passphrase_protected: identity.passphrase.is_some(),
            },
            Key::Unavailable(reason) => SshKey::Unavailable {
                reason: reason.clone(),
            },
        };
        SshInfo {
            key,
            host_keys: self.hosts.policy(),
            trusted_hosts: self.hosts.trusted(),
        }
    }

    fn log(&self) {
        match &*self.key() {
            Key::Ready(identity) => tracing::info!(
                "SSH key for package sources: {}\n    \
                 Add this public key to the git remotes AURCache clones over SSH:\n    {}",
                identity.private_key.display(),
                identity.public_key_line()
            ),
            Key::Unavailable(reason) => tracing::error!(
                "No SSH key for package sources, so packages from SSH remotes cannot be \
                 fetched: {reason}"
            ),
        }
    }
}

/// What a restore does with the server's SSH state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SshRestoreMode {
    /// Secrets are not taken: nothing changes.
    Keep,
    /// The dump's secrets are taken into this server as it is.
    Take,
    /// The server is cleared first: the result is a fresh install plus what
    /// the dump carries.
    Fresh,
}

/// What a restore will do with the server's SSH state, checked before
/// anything is written.
///
/// Deliberately not `Debug`: it holds the private key it is to write.
pub struct SshPlan {
    key: KeyPlan,
    known_hosts: HostsPlan,
}

enum KeyPlan {
    Keep,
    /// The dump's key, checked to open, into the server's own key file.
    Install {
        own: PathBuf,
        private_key: Zeroizing<String>,
        public_key: PublicKey,
    },
    /// The dump's key into the server's own key file, while the key in use
    /// stays the one the operator supplied.
    Beside {
        own: PathBuf,
        private_key: Zeroizing<String>,
        public_key: PublicKey,
        configured: PathBuf,
    },
    /// The operator's key file is where the dump's key would go: left alone.
    /// The dump's public half is known only if its key could be read.
    Skip {
        public_key: Option<PublicKey>,
        configured: PathBuf,
    },
    /// A fresh install has no key of its own yet: remove it, and generate one
    /// if it is the key in use.
    Reset {
        own: PathBuf,
        regenerate: bool,
    },
}

enum HostsPlan {
    Keep,
    /// The operator pins host keys in a file of their own.
    Pinned {
        file: PathBuf,
    },
    /// Add the dump's entries to the server's own file.
    Merge {
        file: PathBuf,
        text: String,
    },
    /// Make the server's own file the dump's, or empty, as a fresh install
    /// starts.
    Replace {
        file: PathBuf,
        text: String,
    },
}

/// What a restore did with the key a dump carried.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeyRestored {
    /// Nothing to do: secrets not taken, or none carried.
    Untouched,
    /// The server's own key file already held it.
    Unchanged,
    /// Now the server's own key, and the one it clones with.
    Installed { fingerprint: String },
    /// A fresh install's own key, generated in place of the old one.
    Regenerated { fingerprint: String },
    /// The server's own key file is gone, as on a fresh install; the key in
    /// use is the operator's.
    Removed,
    /// In the server's own key file, while the key it clones with is the one
    /// `AURCACHE_GIT_SSH_KEY` names.
    Beside {
        fingerprint: String,
        configured: PathBuf,
        same_key: bool,
    },
    /// Not written: the server's own key file is the operator's.
    Skipped {
        fingerprint: String,
        configured: PathBuf,
        same_key: bool,
    },
}

/// What a restore did with the host keys a dump carried.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HostsRestored {
    Untouched,
    /// The dump's entries this server lacked were added.
    Merged {
        file: PathBuf,
        added: usize,
    },
    /// The server's own file is now the dump's, as on a fresh install.
    Replaced {
        file: PathBuf,
    },
    /// Left alone: the operator pins host keys in a file of their own.
    Pinned {
        file: PathBuf,
    },
}

/// What a restore did with a dump's SSH state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SshRestored {
    pub key: KeyRestored,
    pub known_hosts: HostsRestored,
}

/// A restore that failed part of the way: what it had changed already, and
/// why it stopped.
#[derive(Debug)]
pub struct PartialRestore {
    pub known_hosts: HostsRestored,
    pub error: anyhow::Error,
}

impl SshAccess {
    /// What a dump with secrets carries of SSH: the key in use, generated or
    /// supplied, byte for byte as it is stored, and the host keys trusted on
    /// first use.
    ///
    /// Read from the files, never from what is loaded: nothing hands out a
    /// key already in memory. The passphrase is never part of it.
    pub fn export(&self) -> anyhow::Result<DumpSsh> {
        let Some(config) = &self.config else {
            return Ok(DumpSsh::default());
        };
        let path = config.key.path();
        let key = read_optional(path)?.map(|private_key| DumpSshKey {
            private_key,
            public_key: match &*self.key() {
                Key::Ready(identity) => Some(identity.public_key_line()),
                Key::Unavailable(_) => fs::read_to_string(public_key_path(path))
                    .ok()
                    .map(|line| line.trim().to_string()),
            },
        });
        if key.is_some() && self.identity().is_ok_and(|i| i.passphrase.is_none()) {
            tracing::warn!(
                "The dump carries the SSH key {} without a passphrase: whoever holds the dump \
                 can read every repository the key was added to",
                path.display()
            );
        }
        let known_hosts = match &config.hosts {
            HostKeySource::TrustOnFirstUse(file) => read_optional(file)?,
            HostKeySource::Pinned(_) => None,
        };
        Ok(DumpSsh { key, known_hosts })
    }

    /// Check what a restore would do with `dump`'s SSH state, writing
    /// nothing; or say why it cannot be done, so the restore is refused
    /// before anything is touched.
    ///
    /// The dump's key must open here: a protected key needs this server's
    /// `AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE` to hold its passphrase. A key
    /// the operator supplied is never written, even where it is the server's
    /// own key file. Host keys are merged into the server's own file, and a
    /// dump that names a host this server knows by another key is refused;
    /// with [`SshRestoreMode::Fresh`] the file is the dump's.
    pub fn plan_restore(
        &self,
        dump: Option<&DumpSsh>,
        mode: SshRestoreMode,
    ) -> anyhow::Result<SshPlan> {
        let keep = SshPlan {
            key: KeyPlan::Keep,
            known_hosts: HostsPlan::Keep,
        };
        if mode == SshRestoreMode::Keep {
            return Ok(keep);
        }
        let Some(config) = &self.config else {
            if dump.is_some_and(|d| d.key.is_some() || d.known_hosts.is_some()) {
                bail!("this server was started without an SSH configuration to restore into");
            }
            return Ok(keep);
        };
        let empty = DumpSsh::default();
        let dump = dump.unwrap_or(&empty);
        Ok(SshPlan {
            key: plan_key(config, dump.key.as_ref(), mode)?,
            known_hosts: plan_hosts(config, dump.known_hosts.as_deref(), mode)?,
        })
    }

    /// Carry out a plan [`Self::plan_restore`] made, and use the key it put in
    /// place at once.
    ///
    /// The host keys go first: their merge is checked again under the lock
    /// and may still refuse, and refusing then must leave the key as it was.
    /// A failure after that says what had changed already.
    pub fn apply_restore(&self, plan: SshPlan) -> Result<SshRestored, PartialRestore> {
        let known_hosts = self
            .apply_hosts(plan.known_hosts)
            .map_err(|error| PartialRestore {
                known_hosts: HostsRestored::Untouched,
                error,
            })?;
        match self.apply_key(plan.key) {
            Ok(key) => Ok(SshRestored { key, known_hosts }),
            Err(error) => Err(PartialRestore { known_hosts, error }),
        }
    }

    fn apply_hosts(&self, plan: HostsPlan) -> anyhow::Result<HostsRestored> {
        Ok(match plan {
            HostsPlan::Keep => HostsRestored::Untouched,
            HostsPlan::Pinned { file } => HostsRestored::Pinned { file },
            HostsPlan::Merge { file, text } => HostsRestored::Merged {
                added: self.hosts.merge(&file, &text)?,
                file,
            },
            HostsPlan::Replace { file, text } => {
                self.hosts.replace(&file, &text)?;
                HostsRestored::Replaced { file }
            }
        })
    }

    fn apply_key(&self, plan: KeyPlan) -> anyhow::Result<KeyRestored> {
        Ok(match plan {
            KeyPlan::Keep => KeyRestored::Untouched,
            KeyPlan::Install {
                own,
                private_key,
                public_key,
            } => {
                if !install_key(&own, &private_key, &public_key)? {
                    KeyRestored::Unchanged
                } else {
                    self.reload();
                    // Checked to open before it was written; said so only once
                    // the server has loaded it as the key it clones with.
                    match self.identity() {
                        Ok(identity) if identity.public_key.key_data() == public_key.key_data() => {
                            KeyRestored::Installed {
                                fingerprint: identity.fingerprint(),
                            }
                        }
                        Ok(_) => bail!(
                            "the dump's SSH key was written to {}, but the server loaded \
                             another key from it",
                            own.display()
                        ),
                        Err(reason) => bail!(
                            "the dump's SSH key was written to {}, replacing the key there, \
                             but the server cannot use it: {reason}",
                            own.display()
                        ),
                    }
                }
            }
            KeyPlan::Beside {
                own,
                private_key,
                public_key,
                configured,
            } => {
                install_key(&own, &private_key, &public_key)?;
                KeyRestored::Beside {
                    fingerprint: public_key.fingerprint(HashAlg::Sha256).to_string(),
                    same_key: self.uses(&public_key),
                    configured,
                }
            }
            KeyPlan::Skip {
                public_key,
                configured,
            } => KeyRestored::Skipped {
                fingerprint: public_key.as_ref().map_or_else(
                    || "an unreadable key".to_string(),
                    |k| k.fingerprint(HashAlg::Sha256).to_string(),
                ),
                same_key: public_key.as_ref().is_some_and(|k| self.uses(k)),
                configured,
            },
            KeyPlan::Reset { own, regenerate } => {
                remove_optional(&own)?;
                remove_optional(&public_key_path(&own))?;
                if regenerate {
                    self.reload();
                    match self.identity() {
                        Ok(identity) => KeyRestored::Regenerated {
                            fingerprint: identity.fingerprint(),
                        },
                        Err(reason) => bail!(
                            "the server's own SSH key was removed, but a fresh one could not \
                             be generated: {reason}"
                        ),
                    }
                } else {
                    KeyRestored::Removed
                }
            }
        })
    }

    /// Load the configured key again, as a restore that replaced it needs.
    fn reload(&self) {
        let Some(config) = &self.config else { return };
        let reloaded = load_key(config);
        *self
            .key
            .write()
            .unwrap_or_else(std::sync::PoisonError::into_inner) = reloaded;
    }

    /// Whether the key this server clones with is `public`.
    fn uses(&self, public: &PublicKey) -> bool {
        self.identity()
            .is_ok_and(|identity| identity.public_key.key_data() == public.key_data())
    }
}

/// What to do with the server's key, given the one a dump carries.
fn plan_key(
    config: &SshConfig,
    carried: Option<&DumpSshKey>,
    mode: SshRestoreMode,
) -> anyhow::Result<KeyPlan> {
    // Where the server keeps a key of its own. For a generated key that is the
    // key in use; beside a supplied one it waits, unused.
    let own = match &config.key {
        KeySource::Generated(path) => path.clone(),
        KeySource::Provided(_) => config.dir.join(KEY_FILE),
    };
    let configured = match &config.key {
        KeySource::Provided(path) => Some(path.clone()),
        KeySource::Generated(_) => None,
    };
    let Some(carried) = carried else {
        return Ok(match (mode, configured) {
            (SshRestoreMode::Fresh, None) => {
                probe_writable(&own)?;
                KeyPlan::Reset {
                    own,
                    regenerate: true,
                }
            }
            (SshRestoreMode::Fresh, Some(configured))
                if own.exists() && !same_file(&own, &configured) =>
            {
                probe_writable(&own)?;
                KeyPlan::Reset {
                    own,
                    regenerate: false,
                }
            }
            _ => KeyPlan::Keep,
        });
    };

    // What is checked is what will be written, and as it will be used.
    let file = key_file(carried.private_key.as_bytes(), || {
        match &carried.public_key {
            Some(line) => PublicKey::from_openssh(line.trim())
                .context("the dump's SSH public key does not parse"),
            None => bail!(
                "the dump's SSH key is not in OpenSSH's format, and the dump carries no public \
                 half to tell which key it is"
            ),
        }
    });

    // The operator's key file is where the dump's key would go: nothing is
    // written, so nothing about the dump's key is demanded either.
    if let Some(configured) = configured.as_ref().filter(|c| same_file(&own, c)) {
        return Ok(KeyPlan::Skip {
            public_key: file.ok().map(|f| f.public_key),
            configured: configured.clone(),
        });
    }

    let file = file?;
    // Only a key in OpenSSH's format can be shown to be a key, and to open,
    // before it is written. One in an older format would be taken on its
    // `.pub`'s word, and could replace a working key with nothing usable.
    if matches!(
        file.protection,
        Protection::Legacy | Protection::LegacyEncrypted
    ) {
        bail!(
            "the dump's SSH key is in an older format, which cannot be checked before it is \
             installed; convert it with `ssh-keygen -p -f <key>` on the server it came from, \
             and take the dump again"
        );
    }
    let passphrase = config
        .passphrase_file
        .as_deref()
        .map(Passphrase::read)
        .transpose()?;
    // A server that protects its key with a passphrase keeps an unprotected
    // dump key protected with that passphrase, rather than unprotected on disk.
    let private_key = match (&file.protection, &passphrase) {
        (Protection::None, Some(passphrase)) => lock(&carried.private_key, passphrase)?,
        _ => Zeroizing::new(carried.private_key.clone()),
    };
    let public_key = file.public_key.clone();

    Ok(match configured {
        // The key in use from now on: it must open with this server's
        // passphrase, if it needs one.
        None => {
            if !matches!(file.protection, Protection::None) {
                unlock(
                    &file,
                    passphrase,
                    &"the dump's SSH key",
                    config.passphrase_file.as_deref(),
                )?;
            }
            probe_writable(&own)?;
            KeyPlan::Install {
                own,
                private_key,
                public_key,
            }
        }
        // Written beside the operator's key and not used. The passphrase that
        // would open it, were it ever the key in use, is this server's; it is
        // checked when there is one, and not demanded when there is not.
        Some(configured) => {
            if passphrase.is_some() && !matches!(file.protection, Protection::None) {
                unlock(
                    &file,
                    passphrase,
                    &"the dump's SSH key",
                    config.passphrase_file.as_deref(),
                )?;
            }
            probe_writable(&own)?;
            KeyPlan::Beside {
                own,
                private_key,
                public_key,
                configured,
            }
        }
    })
}

/// `pem`, an unprotected OpenSSH key, protected with `passphrase`.
fn lock(pem: &str, passphrase: &Passphrase) -> anyhow::Result<Zeroizing<String>> {
    let key = PrivateKey::from_openssh(pem).context("reading the dump's SSH key")?;
    let locked = key
        .encrypt(&mut ssh_key::rand_core::OsRng, passphrase.as_str())
        .context("protecting the dump's SSH key with this server's passphrase")?;
    locked
        .to_openssh(LineEnding::LF)
        .context("encoding the dump's SSH key")
}

/// What to do with the server's `known_hosts`, given the one a dump carries.
fn plan_hosts(
    config: &SshConfig,
    carried: Option<&str>,
    mode: SshRestoreMode,
) -> anyhow::Result<HostsPlan> {
    let file = match &config.hosts {
        HostKeySource::Pinned(file) => {
            return Ok(match carried {
                Some(_) => HostsPlan::Pinned { file: file.clone() },
                None => HostsPlan::Keep,
            });
        }
        HostKeySource::TrustOnFirstUse(file) => file.clone(),
    };
    match (mode, carried) {
        (SshRestoreMode::Fresh, carried) => {
            probe_writable(&file)?;
            Ok(HostsPlan::Replace {
                file,
                text: carried.unwrap_or_default().to_string(),
            })
        }
        (_, None) => Ok(HostsPlan::Keep),
        (_, Some(text)) => {
            let ours = read_optional(&file)?.unwrap_or_default();
            mergeable(&read_entries(&file)?, &ours, text)?;
            probe_writable(&file)?;
            Ok(HostsPlan::Merge {
                file,
                text: text.to_string(),
            })
        }
    }
}

/// The lines of `carried` to add to the `known_hosts` `ours` was read from,
/// or why the two cannot be merged.
///
/// An entry naming a host `ours` holds to another key of the same type is
/// refused: merging it would let a restore move trust backwards. Another
/// type is no conflict -- OpenSSH keeps one key per type, and GitHub has
/// several. A pattern entry (`*`, `?`) is compared under each name `ours`
/// writes plainly that it matches, and left out when `ours` has names it
/// cannot list. A hashed entry is compared under each name `ours` writes
/// plainly, hashed with that entry's salt; one that matches none of them names
/// a host `ours` does not know plainly, which is safe to add only when `ours`
/// holds no hashed or pattern entries either, since those could cover it.
/// Otherwise it is left out, as is a line that does not parse.
fn mergeable(ours: &[Entry], ours_text: &str, carried: &str) -> anyhow::Result<Vec<String>> {
    let have: std::collections::HashSet<&str> = ours_text.lines().map(str::trim).collect();
    let plain_names: Vec<String> = ours
        .iter()
        .filter_map(|e| match e.host_patterns() {
            HostPatterns::Patterns(patterns) => Some(patterns),
            HostPatterns::HashedName { .. } => None,
        })
        .flatten()
        .filter(|p| !p.starts_with('!') && !is_glob(p))
        .map(|p| p.to_ascii_lowercase())
        .collect();
    let ours_hashed = ours
        .iter()
        .any(|e| matches!(e.host_patterns(), HostPatterns::HashedName { .. }));
    // Names this server holds that cannot be listed: hashed ones, and
    // patterns of its own.
    let ours_unlisted = ours_hashed
        || ours.iter().any(|e| match e.host_patterns() {
            HostPatterns::Patterns(patterns) => patterns.iter().any(|p| is_glob(p)),
            HostPatterns::HashedName { .. } => false,
        });

    let mut lines = Vec::new();
    for line in carried.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') || have.contains(line) {
            continue;
        }
        let Ok(entry) = line.parse::<Entry>() else {
            tracing::warn!("Leaving out an entry of the dump's known_hosts that does not parse");
            continue;
        };
        if entry.marker().is_none() {
            let names: Vec<String> = match entry.host_patterns() {
                HostPatterns::Patterns(patterns) => {
                    // A pattern names every host it matches: each this server
                    // knows is compared. One it cannot list could be among
                    // them, so then the entry is left out.
                    if patterns.iter().any(|p| is_glob(p)) && ours_unlisted {
                        tracing::warn!(
                            "Leaving out a pattern entry of the dump's known_hosts: this \
                             server's own hashed or pattern entries cannot be compared with it"
                        );
                        continue;
                    }
                    let mut names: Vec<String> = patterns
                        .iter()
                        .filter(|p| !p.starts_with('!') && !is_glob(p))
                        .map(|p| p.to_ascii_lowercase())
                        .collect();
                    names.extend(
                        plain_names
                            .iter()
                            .filter(|name| self::names(entry.host_patterns(), name))
                            .cloned(),
                    );
                    names
                }
                hashed @ HostPatterns::HashedName { .. } => {
                    let resolved: Vec<String> = plain_names
                        .iter()
                        .filter(|name| names(hashed, name))
                        .cloned()
                        .collect();
                    // One that names none of them could name a host only
                    // this server's hashed or pattern entries cover.
                    if resolved.is_empty() && ours_unlisted {
                        tracing::warn!(
                            "Leaving out a hashed entry of the dump's known_hosts: this \
                             server's own hashed or pattern entries cannot be compared with it"
                        );
                        continue;
                    }
                    resolved
                }
            };
            for name in &names {
                same_type_conflict(ours, name, entry.public_key())?;
            }
        }
        lines.push(line.to_string());
    }
    Ok(lines)
}

/// Whether a `known_hosts` host pattern matches more than one name.
fn is_glob(pattern: &str) -> bool {
    pattern.contains(['*', '?'])
}

/// Refuse `presented` for `name` when `ours` holds another key of the same
/// type for it, and not this one.
fn same_type_conflict(ours: &[Entry], name: &str, presented: &PublicKey) -> anyhow::Result<()> {
    let same_type: Vec<&Entry> = ours
        .iter()
        .filter(|e| e.marker().is_none() && names(e.host_patterns(), name))
        .filter(|e| e.public_key().algorithm() == presented.algorithm())
        .collect();
    if same_type.is_empty()
        || same_type
            .iter()
            .any(|e| e.public_key().key_data() == presented.key_data())
    {
        return Ok(());
    }
    bail!(
        "the dump trusts {} {} for {name}, but this server trusts another key of that type \
         for it ({}); remove one of them before restoring",
        presented.algorithm(),
        presented.fingerprint(HashAlg::Sha256),
        same_type
            .iter()
            .map(|e| e.public_key().fingerprint(HashAlg::Sha256).to_string())
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// Write `private_key` to `own` and its public half beside it; `false` when
/// `own` already held exactly that key.
fn install_key(own: &Path, private_key: &str, public_key: &PublicKey) -> anyhow::Result<bool> {
    if fs::read(own).ok().as_deref() == Some(private_key.as_bytes()) {
        return Ok(false);
    }
    create_private_dir(own)?;
    aurcache_common::fs::write_private(own, private_key.as_bytes())
        .with_context(|| format!("writing {}", own.display()))?;
    let pub_path = public_key_path(own);
    fs::write(&pub_path, format!("{}\n", public_key.to_openssh()?))
        .with_context(|| format!("writing {}", pub_path.display()))?;
    Ok(true)
}

/// Whether `a` and `b` are one file, through any symlinks; for a path that
/// does not exist yet, by its parent directory's real path.
fn same_file(a: &Path, b: &Path) -> bool {
    real_path(a) == real_path(b)
}

fn real_path(path: &Path) -> PathBuf {
    if let Ok(real) = fs::canonicalize(path) {
        return real;
    }
    match (path.parent(), path.file_name()) {
        (Some(parent), Some(name)) => fs::canonicalize(if parent.as_os_str().is_empty() {
            Path::new(".")
        } else {
            parent
        })
        .map_or_else(|_| path.to_path_buf(), |dir| dir.join(name)),
        _ => path.to_path_buf(),
    }
}

/// Check that `file` can be written, before a restore writes anything: the
/// nearest directory on its way that exists takes a file and gives it back.
fn probe_writable(file: &Path) -> anyhow::Result<()> {
    let dir = file
        .ancestors()
        .skip(1)
        .map(|d| {
            if d.as_os_str().is_empty() {
                Path::new(".")
            } else {
                d
            }
        })
        .find(|d| d.is_dir())
        .unwrap_or_else(|| Path::new("."));
    let probe = dir.join(format!(".aurcache-restore-probe-{}", std::process::id()));
    fs::write(&probe, b"")
        .and_then(|()| fs::remove_file(&probe))
        .with_context(|| {
            format!(
                "{} cannot be written, so {} could not be restored",
                dir.display(),
                file.display()
            )
        })
}

/// Remove a file, which may already be gone.
fn remove_optional(path: &Path) -> anyhow::Result<()> {
    match fs::remove_file(path) {
        Err(e) if e.kind() != std::io::ErrorKind::NotFound => {
            Err(e).with_context(|| format!("removing {}", path.display()))
        }
        _ => Ok(()),
    }
}

/// A file's contents, or `None` when there is no such file.
fn read_optional(path: &Path) -> anyhow::Result<Option<String>> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// Create the directory `file` goes in, closed to other users.
fn create_private_dir(file: &Path) -> anyhow::Result<()> {
    let Some(dir) = file.parent().filter(|d| !d.as_os_str().is_empty()) else {
        return Ok(());
    };
    fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(dir, fs::Permissions::from_mode(0o700))
            .with_context(|| format!("closing {} to other users", dir.display()))?;
    }
    Ok(())
}

/// The key `config` names, or why it cannot be used: none at all when the
/// linked libgit2 could not offer one.
fn load_key(config: &SshConfig) -> Key {
    if let Some(reason) = SshBackend::linked().unusable() {
        return Key::Unavailable(reason);
    }
    match ensure(&config.key, config.passphrase_file.as_deref()) {
        Ok(identity) => Key::Ready(identity),
        Err(e) => Key::Unavailable(format!("{e:#}")),
    }
}

/// Load the key `source` names, generating it first when it is ours, and
/// check it opens with the passphrase in `passphrase_file`, if any.
///
/// A [`KeySource::Provided`] key is never touched: if it is missing that is an
/// operator error, and generating a different key in its place would produce
/// authentication failures that look like the remote's fault.
fn ensure(source: &KeySource, passphrase_file: Option<&Path>) -> anyhow::Result<Identity> {
    let passphrase = passphrase_file.map(Passphrase::read).transpose()?;
    let path = source.path();
    match source {
        KeySource::Provided(_) if !path.exists() => bail!(
            "{AURCACHE_GIT_SSH_KEY} points at {}, which does not exist",
            path.display()
        ),
        KeySource::Provided(_) => {}
        KeySource::Generated(_) if !path.exists() => {
            generate(path)?;
            tracing::info!(
                "Generated an SSH key for package sources at {}",
                path.display()
            );
        }
        KeySource::Generated(_) => {}
    }
    let file = read_key(path)?;
    let passphrase = unlock(&file, passphrase, &path.display(), passphrase_file)?;
    Ok(Identity {
        private_key: path.to_path_buf(),
        public_key: file.public_key,
        origin: source.origin(),
        passphrase,
    })
}

/// Generate an ed25519 key at `path`, private to this user, with its public
/// half beside it as OpenSSH names it.
fn generate(path: &Path) -> anyhow::Result<()> {
    create_private_dir(path)?;
    let mut key = PrivateKey::random(&mut ssh_key::rand_core::OsRng, ssh_key::Algorithm::Ed25519)
        .context("generating an SSH key")?;
    key.set_comment(KEY_COMMENT);
    let private = key
        .to_openssh(LineEnding::LF)
        .context("encoding the SSH key")?;
    aurcache_common::fs::write_private(path, private.as_bytes())
        .with_context(|| format!("writing {}", path.display()))?;
    let public = key
        .public_key()
        .to_openssh()
        .context("encoding the public key")?;
    fs::write(public_key_path(path), format!("{public}\n"))
        .with_context(|| format!("writing {}", public_key_path(path).display()))?;
    Ok(())
}

/// Whether a key file needs a passphrase.
enum Protection {
    None,
    /// Encrypted, in OpenSSH's format: the key to try a passphrase on.
    Encrypted(Box<PrivateKey>),
    /// In an older format, which only libssh2 reads, and not marked
    /// encrypted.
    Legacy,
    /// In an older format whose header says it is encrypted. Whether a
    /// passphrase opens it only libssh2 can tell.
    LegacyEncrypted,
}

/// What a private key file says before it is opened.
struct KeyFile {
    public_key: PublicKey,
    protection: Protection,
}

/// The public half of the private key at `path`, and whether it is
/// encrypted.
///
/// A key in an older format has its `.pub` beside it read for the public
/// half.
fn read_key(path: &Path) -> anyhow::Result<KeyFile> {
    let pem =
        Zeroizing::new(fs::read(path).with_context(|| format!("reading {}", path.display()))?);
    key_file(&pem, || {
        let pub_path = public_key_path(path);
        let line = fs::read_to_string(&pub_path).with_context(|| {
            format!(
                "{} is not an OpenSSH private key, and there is no {} to read its \
                 public half from",
                path.display(),
                pub_path.display()
            )
        })?;
        PublicKey::from_openssh(line.trim())
            .with_context(|| format!("{} is not an SSH public key", pub_path.display()))
    })
}

/// What the private key `pem` says of itself.
///
/// Read off the key when it is in OpenSSH's format, which carries the public
/// key in the clear even when the private half is encrypted; `public` gives it
/// for a key in an older format.
fn key_file(
    pem: &[u8],
    public: impl FnOnce() -> anyhow::Result<PublicKey>,
) -> anyhow::Result<KeyFile> {
    Ok(match PrivateKey::from_openssh(pem) {
        Ok(key) => KeyFile {
            public_key: key.public_key().clone(),
            protection: if key.is_encrypted() {
                Protection::Encrypted(Box::new(key))
            } else {
                Protection::None
            },
        },
        Err(_) => KeyFile {
            public_key: public()?,
            protection: if String::from_utf8_lossy(pem).contains("ENCRYPTED") {
                Protection::LegacyEncrypted
            } else {
                Protection::Legacy
            },
        },
    })
}

/// The passphrase `file` needs, checked to open it when the format allows;
/// or why it cannot be opened. `key` names it in the reason.
fn unlock(
    file: &KeyFile,
    passphrase: Option<Passphrase>,
    key: &dyn std::fmt::Display,
    passphrase_file: Option<&Path>,
) -> anyhow::Result<Option<Passphrase>> {
    match (&file.protection, passphrase) {
        (Protection::Encrypted(encrypted), Some(passphrase)) => {
            encrypted
                .decrypt(passphrase.as_str().as_bytes())
                .map_err(|_| {
                    anyhow::anyhow!(
                        "the passphrase in {} does not open {key}",
                        passphrase_file.map_or_else(String::new, |p| p.display().to_string()),
                    )
                })?;
            Ok(Some(passphrase))
        }
        (Protection::Encrypted(_) | Protection::LegacyEncrypted, None) => bail!(
            "{key} is protected by a passphrase; give it to the server in a file named by \
             {AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE}"
        ),
        (Protection::None | Protection::Legacy, Some(_)) => {
            tracing::warn!(
                "{AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE} is set, but {key} has no passphrase; \
                 ignoring it"
            );
            Ok(None)
        }
        // libssh2 is the one to tell whether the passphrase opens it.
        (Protection::LegacyEncrypted, Some(passphrase)) => Ok(Some(passphrase)),
        (Protection::None | Protection::Legacy, None) => Ok(None),
    }
}

/// Public-key path for a private key, by OpenSSH's `.pub` convention.
fn public_key_path(private: &Path) -> PathBuf {
    let mut name = private.as_os_str().to_os_string();
    name.push(".pub");
    PathBuf::from(name)
}

/// What a `known_hosts` file says of the key a host presented.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HostKeyCheck {
    /// The file lists this key for this host.
    Known,
    /// The file says nothing of this host.
    Unknown,
    /// The file lists another key of this type for this host, and not this
    /// one.
    Changed {
        /// The fingerprints of what it lists, to compare against.
        recorded: Vec<String>,
    },
    /// The file lists keys for this host, but none of this type: the host
    /// offered a type nobody recorded.
    OtherTypes {
        /// The types it does list.
        recorded: Vec<String>,
    },
    /// The file marks this key `@revoked`.
    Revoked,
}

/// The host keys the server trusts, and the policy for one it has not seen.
#[derive(Debug)]
pub(crate) struct HostKeys {
    source: HostKeySource,
    /// Held while a host is looked up and recorded, so two first contacts
    /// with one host write one line between them.
    record: Mutex<()>,
    /// Where a host trusted on first use is recorded for people to check.
    log: ActivityLog,
}

impl HostKeys {
    fn new(source: HostKeySource) -> Self {
        Self {
            source,
            record: Mutex::new(()),
            log: ActivityLog::discarding(),
        }
    }

    /// Make the server's own `known_hosts` `text`, as a fresh install
    /// restored from a dump starts.
    fn replace(&self, file: &Path, text: &str) -> anyhow::Result<()> {
        let _guard = self
            .record
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        create_private_dir(file)?;
        aurcache_common::fs::write_private(file, text.as_bytes())
            .with_context(|| format!("writing {}", file.display()))
    }

    /// Add the lines of `text` the server's own `known_hosts` lacks, keeping
    /// every entry it has; how many were added.
    ///
    /// Checked again for conflicts under the lock, since a host may have been
    /// recorded since the restore was planned.
    fn merge(&self, file: &Path, text: &str) -> anyhow::Result<usize> {
        let _guard = self
            .record
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let mut merged = read_optional(file)?.unwrap_or_default();
        let lines = mergeable(&read_entries(file)?, &merged, text)?;
        let added = lines.len();
        for line in lines {
            if !merged.is_empty() && !merged.ends_with('\n') {
                merged.push('\n');
            }
            merged.push_str(&line);
            merged.push('\n');
        }
        if added > 0 {
            create_private_dir(file)?;
            aurcache_common::fs::write_private(file, merged.as_bytes())
                .with_context(|| format!("writing {}", file.display()))?;
        }
        Ok(added)
    }

    fn policy(&self) -> HostKeyPolicy {
        match self.source {
            HostKeySource::Pinned(_) => HostKeyPolicy::Pinned,
            HostKeySource::TrustOnFirstUse(_) => HostKeyPolicy::TrustOnFirstUse,
        }
    }

    /// The keys the file vouches for, for people to check their
    /// fingerprints. A line that does not parse is left out here; checking a
    /// host is what reports it.
    fn trusted(&self) -> TrustedHosts {
        let file = self.source.path();
        let _guard = self
            .record
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let text = match fs::read_to_string(file) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(e) => {
                return TrustedHosts::Unreadable {
                    reason: format!("reading {}: {e}", file.display()),
                };
            }
        };
        let hosts = KnownHosts::new(&text)
            .filter_map(Result::ok)
            .filter(|entry| entry.marker().is_none())
            .map(|entry| trusted_host(&entry))
            .collect();
        TrustedHosts::Listed { hosts }
    }

    /// Accept `presented` for `remote`, recording it if this is first contact
    /// and the policy allows that; otherwise say plainly why not and what to do.
    pub(crate) fn verify(&self, remote: &SshRemote, presented: &PublicKey) -> anyhow::Result<()> {
        let name = remote.known_hosts_name();
        let file = self.source.path();
        let fingerprint = presented.fingerprint(HashAlg::Sha256);
        let _guard = self
            .record
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        match check(&read_entries(file)?, &name, presented) {
            HostKeyCheck::Known => Ok(()),
            HostKeyCheck::Revoked => bail!(
                "{name} presented the SSH host key {fingerprint}, which {} marks as revoked",
                file.display()
            ),
            HostKeyCheck::Changed { recorded } => {
                let renew = match self.source {
                    HostKeySource::Pinned(_) => format!(
                        "then {}",
                        on_the_host(&keyscan(remote, file, None), "ssh-keyscan")
                    ),
                    HostKeySource::TrustOnFirstUse(_) => {
                        "and the next attempt records the new one".to_string()
                    }
                };
                bail!(
                    "{name} presented the SSH host key {} {fingerprint}, but {} records \
                     another of that type for it: {}. Someone may be intercepting the \
                     connection. If the host's key really changed, {}, {renew}.",
                    presented.algorithm(),
                    file.display(),
                    recorded.join(", "),
                    forget(&name, file),
                )
            }
            // Not a sign of interception: the host has several keys, and only
            // other types were recorded. Still refused, since nothing vouches
            // for this one.
            HostKeyCheck::OtherTypes { recorded } => bail!(
                "only {} recorded for {name} in {}, and it offered its {} key \
                 ({fingerprint}); record that key too: {}",
                recorded.join(", "),
                file.display(),
                presented.algorithm(),
                on_the_host(&keyscan(remote, file, Some(presented)), "ssh-keyscan"),
            ),
            HostKeyCheck::Unknown => match &self.source {
                HostKeySource::Pinned(_) => bail!(
                    "{name} is not in {AURCACHE_SSH_KNOWN_HOSTS} ({}), so its SSH host key \
                     {fingerprint} is not trusted. If that is the host's key, add it: {}",
                    file.display(),
                    on_the_host(&keyscan(remote, file, None), "ssh-keyscan")
                ),
                HostKeySource::TrustOnFirstUse(_) => {
                    record(file, &name, presented)?;
                    // In the activity log rather than the journal alone: it
                    // is the one fingerprint nothing checked, and someone
                    // should.
                    self.log.emit(Event::SshHostTrusted {
                        host: name,
                        key_type: presented.algorithm().to_string(),
                        fingerprint: fingerprint.to_string(),
                    });
                    Ok(())
                }
            },
        }
    }
}

/// What a `known_hosts` entry vouches for, as the API reports it.
fn trusted_host(entry: &Entry) -> TrustedHost {
    TrustedHost {
        names: match entry.host_patterns() {
            HostPatterns::Patterns(patterns) => Some(patterns.join(",")),
            HostPatterns::HashedName { .. } => None,
        },
        key_type: entry.public_key().algorithm().to_string(),
        fingerprint: entry.public_key().fingerprint(HashAlg::Sha256).to_string(),
    }
}

/// The command, ready to paste into a shell, that appends a host's keys to
/// `file`: all of them, or only those of `only`'s type.
fn keyscan(remote: &SshRemote, file: &Path, only: Option<&PublicKey>) -> String {
    let mut command = vec!["ssh-keyscan".to_string()];
    if let Some(kind) = only.and_then(keyscan_type) {
        command.extend(["-t".to_string(), kind.to_string()]);
    }
    if let Some(port) = remote.port.filter(|&port| port != 22) {
        command.extend(["-p".to_string(), port.to_string()]);
    }
    command.push(quote_argument(&remote.host));
    format!(
        "{} >> {}",
        command.join(" "),
        quote_argument(&file.display().to_string())
    )
}

/// What `ssh-keyscan -t` calls `key`'s type, for the types it can ask for.
fn keyscan_type(key: &PublicKey) -> Option<&'static str> {
    match key.algorithm() {
        ssh_key::Algorithm::Ed25519 => Some("ed25519"),
        ssh_key::Algorithm::Ecdsa { .. } => Some("ecdsa"),
        ssh_key::Algorithm::Rsa { .. } => Some("rsa"),
        _ => None,
    }
}

/// `command`, which runs `tool` on a file the server names, as a refusal
/// suggests it.
///
/// The container images have neither `ssh-keygen` nor `ssh-keyscan`, and the
/// path is the server's own, which in a container is not the host's: so the
/// command is for the host, against its copy of that file.
fn on_the_host(command: &str, tool: &str) -> String {
    format!(
        "`{command}` (in a container, which has no {tool}, on the host against \
         the host's copy of that file)"
    )
}

/// How to remove `name`'s entries from `file`, as a refusal says it.
///
/// `ssh-keygen -R` replaces the file with one owned by whoever runs it, mode
/// `0600`, which the server may no longer read. Deleting the line by hand is
/// the other way, except for a hashed entry, which does not show the name.
fn forget(name: &str, file: &Path) -> String {
    let display = file.display().to_string();
    let command = format!(
        "ssh-keygen -R {} -f {}",
        quote_argument(name),
        quote_argument(&display)
    );
    format!(
        "remove the old entry: delete the line for {name} from {display}, or run {} \
         and restore the file's owner and mode, which ssh-keygen -R does not keep; \
         a hashed entry does not show the name, and only ssh-keygen -R finds it",
        on_the_host(&command, "ssh-keygen"),
    )
}

/// Every entry of the `known_hosts` file at `path`; none when it does not
/// exist yet.
///
/// A line that does not parse is skipped and reported, as OpenSSH does: one
/// unreadable line must not stop every other host from being checked.
fn read_entries(path: &Path) -> anyhow::Result<Vec<Entry>> {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let mut entries = Vec::new();
    for (index, entry) in KnownHosts::new(&text).enumerate() {
        match entry {
            Ok(entry) => entries.push(entry),
            Err(e) => tracing::warn!(
                "Skipping entry {} of {}, which does not parse: {e}",
                index + 1,
                path.display()
            ),
        }
    }
    Ok(entries)
}

/// What `entries` say of `presented` as the key of the host `name`.
#[must_use]
pub fn check(entries: &[Entry], name: &str, presented: &PublicKey) -> HostKeyCheck {
    let applicable: Vec<&Entry> = entries
        .iter()
        .filter(|e| names(e.host_patterns(), name))
        .collect();
    let same = |e: &Entry| e.public_key().key_data() == presented.key_data();
    // A revocation wins wherever it is in the file.
    if applicable
        .iter()
        .any(|e| matches!(e.marker(), Some(Marker::Revoked)) && same(e))
    {
        return HostKeyCheck::Revoked;
    }
    // Certificates are not checked, so a `@cert-authority` line vouches for
    // nothing here.
    let plain: Vec<&Entry> = applicable
        .into_iter()
        .filter(|e| e.marker().is_none())
        .collect();
    if plain.iter().any(|e| same(e)) {
        return HostKeyCheck::Known;
    }
    if plain.is_empty() {
        return HostKeyCheck::Unknown;
    }
    let same_type: Vec<&&Entry> = plain
        .iter()
        .filter(|e| e.public_key().algorithm() == presented.algorithm())
        .collect();
    if same_type.is_empty() {
        let mut recorded: Vec<String> = plain
            .iter()
            .map(|e| e.public_key().algorithm().to_string())
            .collect();
        recorded.sort();
        recorded.dedup();
        return HostKeyCheck::OtherTypes { recorded };
    }
    HostKeyCheck::Changed {
        recorded: same_type
            .iter()
            .map(|e| {
                format!(
                    "{} {}",
                    e.public_key().algorithm(),
                    e.public_key().fingerprint(HashAlg::Sha256)
                )
            })
            .collect(),
    }
}

/// Whether a `known_hosts` entry's host field covers `name`.
///
/// A hashed name matches when the salted HMAC-SHA1 of `name` is its hash. A
/// pattern list matches when one of its patterns does and none of its negated
/// ones (`!pattern`) does.
fn names(patterns: &HostPatterns, name: &str) -> bool {
    match patterns {
        HostPatterns::HashedName { salt, hash } => {
            let Ok(mut mac) = hmac::Hmac::<sha1::Sha1>::new_from_slice(salt) else {
                return false;
            };
            mac.update(name.as_bytes());
            mac.verify_slice(hash).is_ok()
        }
        HostPatterns::Patterns(patterns) => {
            let mut matched = false;
            for pattern in patterns {
                match pattern.strip_prefix('!') {
                    Some(negated) if glob(negated, name) => return false,
                    Some(_) => {}
                    None => matched |= glob(pattern, name),
                }
            }
            matched
        }
    }
}

/// OpenSSH's host pattern match: `*` is any run of characters, `?` any one,
/// and letters match regardless of case.
fn glob(pattern: &str, name: &str) -> bool {
    fn matches(pattern: &[u8], name: &[u8]) -> bool {
        match (pattern.split_first(), name.split_first()) {
            (None, None) => true,
            (Some((b'*', rest)), _) => {
                matches(rest, name) || (!name.is_empty() && matches(pattern, &name[1..]))
            }
            (Some((b'?', rest)), Some((_, name_rest))) => matches(rest, name_rest),
            (Some((p, rest)), Some((n, name_rest))) => {
                p.eq_ignore_ascii_case(n) && matches(rest, name_rest)
            }
            _ => false,
        }
    }
    matches(pattern.as_bytes(), name.as_bytes())
}

/// Append `name`'s key to the server's own `known_hosts`, creating it (and
/// its directory) private to this user.
fn record(file: &Path, name: &str, key: &PublicKey) -> anyhow::Result<()> {
    create_private_dir(file)?;
    let mut key = key.clone();
    key.set_comment("");
    let line = format!("{name} {}\n", key.to_openssh()?);
    let mut options = fs::OpenOptions::new();
    options.create(true).append(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut out = options
        .open(file)
        .with_context(|| format!("opening {}", file.display()))?;
    out.write_all(line.as_bytes())
        .and_then(|()| out.sync_all())
        .with_context(|| format!("recording {name} in {}", file.display()))
}

/// What a PKGBUILD parse must never read: the server's SSH directory, and a
/// key or a passphrase the operator keeps somewhere else.
#[must_use]
pub fn private_paths() -> Vec<PathBuf> {
    let config = SshConfig::configured();
    let mut paths = vec![aurcache_common::fs::ssh_dir()];
    if let KeySource::Provided(key) = config.key {
        paths.push(key);
    }
    paths.extend(config.passphrase_file);
    paths
}

