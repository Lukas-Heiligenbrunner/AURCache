//! The SSH key the server clones package sources with, and the host keys it
//! trusts.
//!
//! A package can come from a git repository over SSH (`git@host:repo.git`),
//! which is what a private repository usually needs. The server clones that
//! repository itself -- it reads the PKGBUILD before any build exists -- so it
//! needs a key of its own. This is not a worker's key: a worker holds one for
//! the sources a PKGBUILD downloads during a build, and the two answer to
//! different remotes.
//!
//! The key, in precedence order:
//!
//! 1. `AURCACHE_GIT_SSH_KEY` names one: it is used as it is, and nothing is
//!    generated. A second, unused key beside it would make "which key is in
//!    use?" ambiguous exactly when an authentication failure is being debugged.
//! 2. Otherwise an ed25519 key is generated under [`ssh_dir`] on first start.
//!    Its public half is logged, shown on the settings page and printed by
//!    `aurcli ssh key`, to be added to the remote as a deploy key.
//!
//! Either may be protected by a passphrase, which
//! `AURCACHE_GIT_SSH_KEY_PASSPHRASE_FILE` names a file holding. It is read
//! once, at start. The generated key is written unprotected: a passphrase the
//! server chose and stored beside the key would protect nothing.
//!
//! Host keys are never taken on trust silently:
//!
//! - `AURCACHE_SSH_KNOWN_HOSTS` names a `known_hosts` file, and only the host
//!   keys in it are trusted. A host it does not list is refused.
//! - Otherwise a host's key is recorded in `known_hosts` under [`ssh_dir`] the
//!   first time the server connects, and logged with its fingerprint; a host
//!   that later presents a different key is refused.
//!
//! [`ssh_dir`]: aurcache_common::fs::ssh_dir

